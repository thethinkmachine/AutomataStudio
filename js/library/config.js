// ══════════════════════════════════════════════════════════════════
//  WHERE THE LIBRARY LIVES
// ══════════════════════════════════════════════════════════════════
// The library is a public GitHub repository of `.automaton` files. Its CI
// analyses every one of them and publishes the result to GitHub Pages: the
// index, the pictures and the website itself. The app reads that site. Pages sends `Access-Control-Allow-
// Origin: *`, rebuilds on every merge, and needs no bot committing generated
// files back into the repository.
//
// The machine files themselves are fetched from jsDelivr, **pinned to the commit
// the index was built from**. Pinned, a CDN cache can never hand back a file
// older than the index that lists it — the hash the index carries is the hash
// of exactly those bytes — where Pages' own CDN may hold a file for minutes
// after a publish. The Pages copy of the same file is the fallback.
// Neither goes through the GitHub API, whose sixty unauthenticated requests an
// hour per IP one classroom behind one NAT would spend in a minute.
//
// Every URL the app, the website and CI build is built here, so the three
// cannot disagree about where an entry is. A reader who wants to point the app
// at a fork, or at a local build served over http while developing, sets
// `localStorage['as.library.base']` — the one override, read once per call.
//
// Import-free: CI builds the website's links with it.

export const LIBRARY_REPO = 'thethinkmachine/automata-library';
export const LIBRARY_BRANCH = 'main';

/** Where the web build of the app is published — the target of "Open in AutomataStudio". */
export const APP_WEB_URL = 'https://thethinkmachine.github.io/AutomataStudio/';

/** The library's own website, generated by its CI onto GitHub Pages. */
export const LIBRARY_SITE_URL = 'https://thethinkmachine.github.io/automata-library/';

/** The desktop app's URL scheme, registered by electron/main.cjs. */
export const APP_PROTOCOL = 'automata-studio';

export const INDEX_FORMAT = 'automata-studio/library-index';
export const INDEX_VERSION = 1;

/** The issue form a submission is filed through (.github/ISSUE_TEMPLATE/submit-machine.yml). */
export const SUBMIT_TEMPLATE = 'submit-machine.yml';

/**
 * GitHub truncates nothing and refuses nothing below this, and past it some
 * browsers and proxies do. A pre-filled issue URL longer than this is not sent;
 * the machine goes on the clipboard instead and the form is opened without it.
 */
export const ISSUE_URL_MAX = 7800;

const OVERRIDE_KEY = 'as.library.base';

function readOverride() {
  try {
    const v = globalThis.localStorage?.getItem(OVERRIDE_KEY);
    return v && /^https?:\/\//.test(v) ? v.replace(/\/?$/, '/') : null;
  } catch {
    return null;
  }
}

/** The base the index, pictures and pages are fetched from, ending in a slash. */
export function libraryBase(site = LIBRARY_SITE_URL) {
  return readOverride() || site;
}

/** Whether the reader has pointed the app somewhere other than the published library. */
export function libraryIsOverridden() {
  return !!readOverride();
}

export function setLibraryOverride(url) {
  try {
    if (url) globalThis.localStorage?.setItem(OVERRIDE_KEY, url);
    else globalThis.localStorage?.removeItem(OVERRIDE_KEY);
  } catch { /* private mode: the default stands */ }
}

/**
 * A path inside the library → a fetchable URL. Each segment is encoded on its
 * own, so a slash stays a separator and a space or a `#` in a filename does not
 * end the URL early.
 */
export function libraryUrl(path, base = libraryBase()) {
  return base + encodePath(path);
}

export function indexUrl(base = libraryBase()) {
  return libraryUrl('index.json', base);
}

/**
 * Where to fetch an entry's file from, in order: jsDelivr at the index's commit,
 * then the site's own copy. With the override set only the second is used — a
 * local build has no commit on GitHub to pin to.
 */
export function entryFileUrls(entry, index, base = libraryBase()) {
  const urls = [];
  const repo = index?.repo || LIBRARY_REPO;
  if (!libraryIsOverridden() && /^[0-9a-f]{7,40}$/.test(index?.commit || '')) {
    urls.push(`https://cdn.jsdelivr.net/gh/${repo}@${index.commit}/${encodePath(entry.path)}`);
  }
  urls.push(libraryUrl(entry.path, base));
  return urls;
}

function encodePath(path) {
  return String(path || '').replace(/^\/+/, '').split('/').map(encodeURIComponent).join('/');
}

export function repoUrl(repo = LIBRARY_REPO) {
  return `https://github.com/${repo}`;
}

/** The file on GitHub, for "view source". */
export function sourceUrl(path, repo = LIBRARY_REPO, branch = LIBRARY_BRANCH) {
  return `${repoUrl(repo)}/blob/${branch}/${String(path || '').split('/').map(encodeURIComponent).join('/')}`;
}

/** An entry's page on the library website. */
export function entryPageUrl(id, site = LIBRARY_SITE_URL) {
  return `${site}m/${encodePath(id)}/`;
}

// ── Deep links ────────────────────────────────────────────────────
//  Three things a link can ask for, in both builds:
//
//    #lib=<id>             open that machine in a tab (the website's button)
//    #library=<id>         show its listing in the Library view
//    #library              open the Library view
//    #collection=<id>      show a collection
//
//  The desktop app receives the same requests as automata-studio://lib/<id>,
//  automata-studio://library/<id>, automata-studio://library and
//  automata-studio://collection/<id> — one parser, two spellings.
//
//  An id is a path under machines/ without the extension, so it may contain
//  slashes. Anything outside [A-Za-z0-9._/-] is refused rather than passed on:
//  an id ends up in a fetch URL, and `..` is refused for the same reason.

const ID_RE = /^[A-Za-z0-9][A-Za-z0-9._/-]{0,199}$/;

export function isLibraryId(id) {
  return typeof id === 'string' && ID_RE.test(id) && !id.split('/').includes('..') && !id.includes('//');
}

/** `#lib=…`, or null when the hash is not a library request. */
export function parseLibraryHash(hash) {
  const h = String(hash || '').replace(/^#/, '');
  if (h === 'library') return { action: 'browse' };
  const m = /^(lib|library|collection)=(.+)$/.exec(h);
  if (!m) return null;
  let id;
  try { id = decodeURIComponent(m[2]); } catch { return null; }
  if (!isLibraryId(id)) return null;
  const action = m[1] === 'lib' ? 'open' : m[1] === 'library' ? 'show' : 'collection';
  return { action, id };
}

/**
 * `#library-source=http://127.0.0.1:8765/` — point the app at a library served
 * on this machine, which is what `npm run library:dev` prints. Only loopback
 * addresses are accepted: a link is something anyone can send, and one that
 * quietly repointed a reader's Library at a stranger's server would show them
 * badges nobody's CI ever earned.
 */
export function parseLibrarySourceHash(hash) {
  const m = /^#?library-source=(.+)$/.exec(String(hash || ''));
  if (!m) return null;
  let url;
  try { url = new URL(decodeURIComponent(m[1])); } catch { return null; }
  if (url.protocol !== 'http:' && url.protocol !== 'https:') return null;
  if (!['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) return null;
  return url.href.replace(/\/?$/, '/');
}

/** `automata-studio://lib/<id>` and friends, or null. */
export function parseLibraryProtocolUrl(url) {
  const m = new RegExp(`^${APP_PROTOCOL}:/*(lib|library|collection)(?:/(.*?))?/?$`).exec(String(url || '').trim());
  if (!m) return null;
  if (!m[2]) return m[1] === 'library' ? { action: 'browse' } : null;
  let id;
  try { id = decodeURIComponent(m[2]); } catch { return null; }
  if (!isLibraryId(id)) return null;
  const action = m[1] === 'lib' ? 'open' : m[1] === 'library' ? 'show' : 'collection';
  return { action, id };
}

/** The web app's link for a request — what the website's buttons point at. */
export function webAppLink(req, app = APP_WEB_URL) {
  if (!req || req.action === 'browse') return `${app}#library`;
  const key = req.action === 'open' ? 'lib' : req.action === 'show' ? 'library' : 'collection';
  return `${app}#${key}=${encodeURIComponent(req.id)}`;
}

/** The desktop app's link for the same request. */
export function protocolLink(req) {
  if (!req || req.action === 'browse') return `${APP_PROTOCOL}://library`;
  const key = req.action === 'open' ? 'lib' : req.action === 'show' ? 'library' : 'collection';
  return `${APP_PROTOCOL}://${key}/${req.id.split('/').map(encodeURIComponent).join('/')}`;
}
