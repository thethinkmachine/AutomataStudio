// ══════════════════════════════════════════════════════════════════
//  CODE GENERATION
// ══════════════════════════════════════════════════════════════════
//  Turns a drawn machine into source you can run, a statechart config
//  you can hand to a runtime, or a test suite you can drop into a
//  project.
//
//  Scope is deliberate. Generating a recogniser is only worth doing if
//  the generated thing decides the same language the canvas does, so
//  these emitters cover exactly the models whose runtime semantics
//  translate faithfully to a few dozen lines of host code:
//
//    DFA            deterministic walk over a transition table
//    NFA, ε-NFA     subset simulation with an ε-closure
//    Moore, Mealy   deterministic walk that emits output
//
//  Stack and tape machines are refused rather than approximated. A
//  "PDA in Python" that silently drops nondeterminism, or a TM whose
//  generated tape is finite, is worse than no output at all — it looks
//  authoritative and is wrong. codegenSupport() is the single place
//  that decision lives, and every emitter routes through it.
//
//  ── styles ───────────────────────────────────────────────────────
//  The same machine emits in three shapes, because the shape that is
//  useful depends on what the code is for:
//
//    table   δ as a data literal, walked by a loop. Compact, and the
//            structure stays visible — the transition function reads
//            back off the page. Best when the machine may be edited.
//
//    switch  no data structure at all; δ becomes nested control flow.
//            This is what a person writes by hand in embedded C or a
//            hot loop, and what a reviewer can follow without holding
//            a table in their head.
//
//    class   an object with the state as a field: reset(), step(), and
//            isAccepting(). The other two consume a whole string; this
//            one accepts input incrementally, which is what a stream,
//            a parser, or a UI driving one symbol per event needs.
//            (C has no classes, so it gets the honest analogue: an
//            opaque struct plus functions taking a pointer to it.)
//
//  Style changes the shape, never the language decided. The generated
//  recogniser is differential-tested against the app's own simulator
//  for every style.
// ══════════════════════════════════════════════════════════════════

const CODEGEN_MODELS = new Set(['DFA', 'NFA', 'ε-NFA', 'Moore', 'Mealy']);
const CODEGEN_STYLES = ['table', 'switch', 'class'];

function codegenStyle(opts) {
  const s = opts && opts.style;
  return CODEGEN_STYLES.includes(s) ? s : 'table';
}

function codegenSupport(ir) {
  if (!ir.states.length) return { ok: false, reason: 'The canvas is empty.' };
  if (!ir.startId) return { ok: false, reason: 'This machine has no start state.' };
  if (!CODEGEN_MODELS.has(ir.machine)) {
    return {
      ok: false,
      reason: `Code generation covers DFA, NFA, ε-NFA, Moore and Mealy machines. `
        + `${ir.machineLabel} needs a stack or a tape, and a generated recogniser that quietly `
        + `dropped either would decide a different language than the one on the canvas.`
    };
  }
  return { ok: true };
}

function codegenIsTransducer(ir) { return ir.machine === 'Moore' || ir.machine === 'Mealy'; }
function codegenIsNondeterministic(ir) { return ir.machine === 'NFA' || ir.machine === 'ε-NFA'; }

// ── shared shaping ────────────────────────────────────────────────
// δ as name → symbol → [target names]. Built once; every language
// emitter walks this rather than the transition array.
function codegenDelta(ir, names) {
  const delta = new Map();
  ir.states.forEach(s => delta.set(names.get(s.id), new Map()));
  ir.transitions.forEach(t => {
    const row = delta.get(names.get(t.from));
    if (!row) return;
    if (!row.has(t.symbol)) row.set(t.symbol, []);
    const dest = names.get(t.to);
    // Mealy carries the emitted symbol on the edge, so the row holds a
    // pair rather than a bare target.
    row.get(t.symbol).push(ir.machine === 'Mealy'
      ? { to: dest, out: t.output == null ? '' : t.output }
      : dest);
  });
  return delta;
}

function codegenNames(ir) {
  return exportUniqueIdents(ir.states, s => s);
}

const CODEGEN_STYLE_NOTE = {
  table: 'δ is a data literal walked by a loop.',
  switch: 'δ is control flow — no transition table.',
  class: 'Stateful object: reset() / step() / isAccepting(), for incremental input.'
};

function codegenBanner(ir, prefix, opts) {
  const lines = [
    `Generated by Automata Playground from a ${ir.machineLabel}.`,
    `States: ${ir.states.length} · Σ = {${ir.sigma.join(', ')}}`,
    ir.isSymbolic
      ? 'Input is read one character at a time.'
      : 'Σ contains multi-character symbols — input is split on whitespace.'
  ];
  if (opts && opts.style) lines.push(CODEGEN_STYLE_NOTE[codegenStyle(opts)]);
  if (opts && opts.extraNote) lines.push(opts.extraNote);
  return lines.map(l => `${prefix} ${l}`).join('\n');
}

// Rows of δ for one state, as [symbol, destinations] pairs — the shape
// the switch emitters walk when writing nested cases.
function codegenRowsFor(delta, stateName) {
  const row = delta.get(stateName);
  return row ? [...row.entries()] : [];
}

// ε-targets for one state, used by the nondeterministic switch emitters
// where the closure cannot read a table.
function codegenEpsTargets(delta, stateName, eps) {
  const row = delta.get(stateName);
  const hit = row && row.get(eps);
  return hit ? hit.slice() : [];
}

function codegenUnsupported(reason, prefix) {
  return `${prefix} Cannot generate code for this machine.\n${prefix}\n`
    + reason.replace(/(.{1,68})(\s|$)/g, (m, chunk) => `${prefix} ${chunk.trim()}\n`);
}

// ── string escaping, per host language ────────────────────────────
function jsStr(s) {
  return JSON.stringify(String(s == null ? '' : s));
}
function pyStr(s) {
  return "'" + String(s == null ? '' : s)
    .replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n') + "'";
}
function javaStr(s) {
  return '"' + String(s == null ? '' : s)
    .replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
}
function xmlAttr(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

// ══════════════════════════════════════════════════════════════════
//  JAVASCRIPT
// ══════════════════════════════════════════════════════════════════
function codegenJavaScript(ir, opts = {}) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '//');
  const style = codegenStyle(opts);
  if (style === 'switch') return codegenJsSwitch(ir, opts);
  if (style === 'class') return codegenJsClass(ir, opts);
  return codegenJsTable(ir, opts);
}

// The JS tokenizer, shared by all three styles.
function codegenJsTokenize(ir) {
  return [
    'function tokenize(input) {',
    ir.isSymbolic ? '  return Array.from(input);' : '  return input.split(/\\s+/).filter(Boolean);',
    '}'
  ];
}

function codegenJsTable(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const accepting = ir.states.filter(s => s.isAccept).map(s => names.get(s.id));
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'table' }));
  out.push('');

  // δ literal
  out.push('const DELTA = {');
  [...delta.entries()].forEach(([from, row]) => {
    if (!row.size) { out.push(`  ${jsStr(from)}: {},`); return; }
    const cells = [...row.entries()].map(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        return `${jsStr(sym)}: { to: ${jsStr(d.to)}, out: ${jsStr(d.out)} }`;
      }
      return `${jsStr(sym)}: ${nd ? `[${dests.map(jsStr).join(', ')}]` : jsStr(dests[0])}`;
    });
    out.push(`  ${jsStr(from)}: { ${cells.join(', ')} },`);
  });
  out.push('};');
  out.push('');
  out.push(`const START = ${jsStr(start)};`);
  if (!codegenIsTransducer(ir)) {
    out.push(`const ACCEPTING = new Set([${accepting.map(jsStr).join(', ')}]);`);
  }
  if (ir.machine === 'Moore') {
    const outputs = ir.states.map(s => `  ${jsStr(names.get(s.id))}: ${jsStr(s.output == null ? '' : s.output)},`);
    out.push('');
    out.push('// Moore output is a property of the state, not the edge.');
    out.push('const OUTPUT = {');
    outputs.forEach(l => out.push(l));
    out.push('};');
  }
  out.push('');
  codegenJsTokenize(ir).forEach(l => out.push(l));
  out.push('');

  if (nd) {
    out.push(`const EPSILON = ${jsStr(eps)};`);
    out.push('');
    out.push('function epsilonClosure(states) {');
    out.push('  const seen = new Set(states);');
    out.push('  const stack = [...states];');
    out.push('  while (stack.length) {');
    out.push('    const s = stack.pop();');
    out.push('    for (const t of (DELTA[s]?.[EPSILON] ?? [])) {');
    out.push('      if (!seen.has(t)) { seen.add(t); stack.push(t); }');
    out.push('    }');
    out.push('  }');
    out.push('  return seen;');
    out.push('}');
    out.push('');
    out.push('function accepts(input) {');
    out.push('  let current = epsilonClosure([START]);');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    const next = new Set();');
    out.push('    for (const s of current) {');
    out.push('      for (const t of (DELTA[s]?.[symbol] ?? [])) next.add(t);');
    out.push('    }');
    out.push('    current = epsilonClosure(next);');
    out.push('    if (!current.size) return false;');
    out.push('  }');
    out.push('  for (const s of current) if (ACCEPTING.has(s)) return true;');
    out.push('  return false;');
    out.push('}');
  } else if (ir.machine === 'Mealy') {
    out.push('function transduce(input) {');
    out.push('  let state = START;');
    out.push('  const output = [];');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    const edge = DELTA[state]?.[symbol];');
    out.push('    if (edge === undefined) return null; // undefined transition');
    out.push('    output.push(edge.out);');
    out.push('    state = edge.to;');
    out.push('  }');
    out.push(`  return output.join(${ir.isSymbolic ? "''" : "' '"});`);
    out.push('}');
  } else if (ir.machine === 'Moore') {
    out.push('function transduce(input) {');
    out.push('  let state = START;');
    out.push('  const output = [OUTPUT[state]];');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    const next = DELTA[state]?.[symbol];');
    out.push('    if (next === undefined) return null; // undefined transition');
    out.push('    state = next;');
    out.push('    output.push(OUTPUT[state]);');
    out.push('  }');
    out.push(`  return output.join(${ir.isSymbolic ? "''" : "' '"});`);
    out.push('}');
  } else {
    out.push('function accepts(input) {');
    out.push('  let state = START;');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    const next = DELTA[state]?.[symbol];');
    out.push('    if (next === undefined) return false; // dead: no such transition');
    out.push('    state = next;');
    out.push('  }');
    out.push('  return ACCEPTING.has(state);');
    out.push('}');
  }

  out.push('');
  const api = codegenIsTransducer(ir) ? 'transduce' : 'accepts';
  out.push(`if (typeof module !== 'undefined') module.exports = { ${api}, DELTA, START };`);
  return out.join('\n');
}

// ── JavaScript: switch ────────────────────────────────────────────
// δ becomes nested switches. Nothing is looked up; a reader follows the
// machine by reading, and a missing case is a visible `default` rather
// than an absent map key.
function codegenJsSwitch(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const order = ir.states.map(s => names.get(s.id));

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'switch' }));
  out.push('');
  out.push(`const START = ${jsStr(start)};`);
  out.push('');
  codegenJsTokenize(ir).forEach(l => out.push(l));
  out.push('');

  // Accepting is a switch too, so the file holds no Set literal at all.
  if (!codegenIsTransducer(ir)) {
    out.push('function isAccepting(state) {');
    out.push('  switch (state) {');
    ir.states.filter(s => s.isAccept).forEach(s => out.push(`    case ${jsStr(names.get(s.id))}:`));
    if (ir.states.some(s => s.isAccept)) out.push('      return true;');
    out.push('    default:');
    out.push('      return false;');
    out.push('  }');
    out.push('}');
    out.push('');
  }

  if (ir.machine === 'Moore') {
    out.push('function outputOf(state) {');
    out.push('  switch (state) {');
    ir.states.forEach(s => {
      out.push(`    case ${jsStr(names.get(s.id))}: return ${jsStr(s.output == null ? '' : s.output)};`);
    });
    out.push('    default: return null;');
    out.push('  }');
    out.push('}');
    out.push('');
  }

  if (nd) {
    // The closure needs ε-targets per state; with no table that is its
    // own switch rather than a lookup.
    out.push('function epsilonTargets(state) {');
    out.push('  switch (state) {');
    order.forEach(name => {
      const targets = codegenEpsTargets(delta, name, eps);
      if (targets.length) out.push(`    case ${jsStr(name)}: return [${targets.map(jsStr).join(', ')}];`);
    });
    out.push('    default: return [];');
    out.push('  }');
    out.push('}');
    out.push('');
    out.push('function epsilonClosure(states) {');
    out.push('  const seen = new Set(states);');
    out.push('  const stack = [...states];');
    out.push('  while (stack.length) {');
    out.push('    for (const t of epsilonTargets(stack.pop())) {');
    out.push('      if (!seen.has(t)) { seen.add(t); stack.push(t); }');
    out.push('    }');
    out.push('  }');
    out.push('  return seen;');
    out.push('}');
    out.push('');
    out.push('// Collects every target of `state` on `symbol` into `next`.');
    out.push('function stepInto(state, symbol, next) {');
    out.push('  switch (state) {');
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name).filter(([sym]) => sym !== eps);
      if (!rows.length) return;
      out.push(`    case ${jsStr(name)}:`);
      out.push('      switch (symbol) {');
      rows.forEach(([sym, dests]) => {
        const adds = dests.map(d => `next.add(${jsStr(d)});`).join(' ');
        out.push(`        case ${jsStr(sym)}: ${adds} break;`);
      });
      out.push('      }');
      out.push('      break;');
    });
    out.push('  }');
    out.push('}');
    out.push('');
    out.push('function accepts(input) {');
    out.push('  let current = epsilonClosure([START]);');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    const next = new Set();');
    out.push('    for (const state of current) stepInto(state, symbol, next);');
    out.push('    current = epsilonClosure(next);');
    out.push('    if (!current.size) return false;');
    out.push('  }');
    out.push('  for (const state of current) if (isAccepting(state)) return true;');
    out.push('  return false;');
    out.push('}');
  } else {
    const transducer = codegenIsTransducer(ir);
    const sep = ir.isSymbolic ? "''" : "' '";
    out.push(transducer ? 'function transduce(input) {' : 'function accepts(input) {');
    out.push('  let state = START;');
    if (transducer) out.push('  const output = [];');
    if (ir.machine === 'Moore') out.push('  output.push(outputOf(state));');
    out.push('  for (const symbol of tokenize(input)) {');
    out.push('    switch (state) {');
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name);
      out.push(`      case ${jsStr(name)}:`);
      if (!rows.length) {
        out.push(`        return ${transducer ? 'null' : 'false'}; // no outgoing transitions`);
        return;
      }
      out.push('        switch (symbol) {');
      rows.forEach(([sym, dests]) => {
        const d = dests[0];
        if (ir.machine === 'Mealy') {
          out.push(`          case ${jsStr(sym)}: output.push(${jsStr(d.out)}); state = ${jsStr(d.to)}; break;`);
        } else {
          out.push(`          case ${jsStr(sym)}: state = ${jsStr(d)}; break;`);
        }
      });
      out.push(`          default: return ${transducer ? 'null' : 'false'};`);
      out.push('        }');
      if (ir.machine === 'Moore') out.push('        output.push(outputOf(state));');
      out.push('        break;');
    });
    out.push(`      default: return ${transducer ? 'null' : 'false'};`);
    out.push('    }');
    out.push('  }');
    out.push(transducer ? `  return output.join(${sep});` : '  return isAccepting(state);');
    out.push('}');
  }

  out.push('');
  const api = codegenIsTransducer(ir) ? 'transduce' : 'accepts';
  out.push(`if (typeof module !== 'undefined') module.exports = { ${api}, START };`);
  return out.join('\n');
}

// ── JavaScript: class ─────────────────────────────────────────────
// The other two styles consume a whole string. This one exposes the
// state so input can arrive one symbol at a time — a stream, a parser,
// a UI dispatching an event per keystroke. accepts()/transduce() are
// still exported so a generated test suite works against any style.
function codegenJsClass(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const accepting = ir.states.filter(s => s.isAccept).map(s => names.get(s.id));
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const transducer = codegenIsTransducer(ir);
  const sep = ir.isSymbolic ? "''" : "' '";

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'class' }));
  out.push('');

  // The table stays module-level rather than becoming static class
  // fields: this style is about the interface, and module consts work
  // in every runtime without relying on class-fields support.
  out.push('const DELTA = {');
  [...delta.entries()].forEach(([from, row]) => {
    if (!row.size) { out.push(`  ${jsStr(from)}: {},`); return; }
    const cells = [...row.entries()].map(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        return `${jsStr(sym)}: { to: ${jsStr(d.to)}, out: ${jsStr(d.out)} }`;
      }
      return `${jsStr(sym)}: ${nd ? `[${dests.map(jsStr).join(', ')}]` : jsStr(dests[0])}`;
    });
    out.push(`  ${jsStr(from)}: { ${cells.join(', ')} },`);
  });
  out.push('};');
  out.push('');
  out.push(`const START = ${jsStr(start)};`);
  if (!transducer) out.push(`const ACCEPTING = new Set([${accepting.map(jsStr).join(', ')}]);`);
  if (ir.machine === 'Moore') {
    out.push('const OUTPUT = {');
    ir.states.forEach(s => out.push(`  ${jsStr(names.get(s.id))}: ${jsStr(s.output == null ? '' : s.output)},`));
    out.push('};');
  }
  if (nd) out.push(`const EPSILON = ${jsStr(eps)};`);
  out.push('');
  codegenJsTokenize(ir).forEach(l => out.push(l));
  out.push('');

  if (nd) {
    out.push('function epsilonClosure(states) {');
    out.push('  const seen = new Set(states);');
    out.push('  const stack = [...states];');
    out.push('  while (stack.length) {');
    out.push('    const s = stack.pop();');
    out.push('    for (const t of (DELTA[s]?.[EPSILON] ?? [])) {');
    out.push('      if (!seen.has(t)) { seen.add(t); stack.push(t); }');
    out.push('    }');
    out.push('  }');
    out.push('  return seen;');
    out.push('}');
    out.push('');
  }

  out.push('class Automaton {');
  out.push('  constructor() {');
  out.push('    this.reset();');
  out.push('  }');
  out.push('');
  out.push('  /** Returns the machine to its start configuration. */');
  out.push('  reset() {');
  if (nd) {
    out.push('    this.current = epsilonClosure([START]);');
  } else {
    out.push('    this.state = START;');
    out.push('    this.dead = false;');
  }
  if (transducer) out.push(`    this.output = [${ir.machine === 'Moore' ? 'OUTPUT[START]' : ''}];`);
  out.push('    return this;');
  out.push('  }');
  out.push('');

  if (nd) {
    out.push('  /** Consumes one symbol. Returns false once no state survives. */');
    out.push('  step(symbol) {');
    out.push('    const next = new Set();');
    out.push('    for (const s of this.current) {');
    out.push('      for (const t of (DELTA[s]?.[symbol] ?? [])) next.add(t);');
    out.push('    }');
    out.push('    this.current = epsilonClosure(next);');
    out.push('    return this.current.size > 0;');
    out.push('  }');
    out.push('');
    out.push('  get isAccepting() {');
    out.push('    for (const s of this.current) if (ACCEPTING.has(s)) return true;');
    out.push('    return false;');
    out.push('  }');
    out.push('');
    out.push('  /** The set of states the machine could currently be in. */');
    out.push('  get states() {');
    out.push('    return [...this.current];');
    out.push('  }');
  } else if (ir.machine === 'Mealy') {
    out.push('  /** Consumes one symbol and returns what it emits, or null. */');
    out.push('  step(symbol) {');
    out.push('    const edge = DELTA[this.state]?.[symbol];');
    out.push('    if (edge === undefined) { this.dead = true; return null; }');
    out.push('    this.state = edge.to;');
    out.push('    this.output.push(edge.out);');
    out.push('    return edge.out;');
    out.push('  }');
  } else if (ir.machine === 'Moore') {
    out.push('  /** Consumes one symbol and returns the new state\'s output. */');
    out.push('  step(symbol) {');
    out.push('    const next = DELTA[this.state]?.[symbol];');
    out.push('    if (next === undefined) { this.dead = true; return null; }');
    out.push('    this.state = next;');
    out.push('    const emitted = OUTPUT[this.state];');
    out.push('    this.output.push(emitted);');
    out.push('    return emitted;');
    out.push('  }');
  } else {
    out.push('  /** Consumes one symbol. Returns false if it kills the run. */');
    out.push('  step(symbol) {');
    out.push('    const next = DELTA[this.state]?.[symbol];');
    out.push('    if (next === undefined) { this.dead = true; return false; }');
    out.push('    this.state = next;');
    out.push('    return true;');
    out.push('  }');
    out.push('');
    out.push('  get isAccepting() {');
    out.push('    return !this.dead && ACCEPTING.has(this.state);');
    out.push('  }');
  }

  out.push('');
  if (transducer) {
    out.push('  /** Runs a whole input. Returns null on an undefined transition. */');
    out.push('  transduce(input) {');
    out.push('    this.reset();');
    out.push('    for (const symbol of tokenize(input)) {');
    out.push('      if (this.step(symbol) === null) return null;');
    out.push('    }');
    out.push(`    return this.output.join(${sep});`);
    out.push('  }');
  } else {
    out.push('  /** Runs a whole input from the start state. */');
    out.push('  accepts(input) {');
    out.push('    this.reset();');
    out.push('    for (const symbol of tokenize(input)) {');
    out.push('      if (!this.step(symbol)) return false;');
    out.push('    }');
    out.push('    return this.isAccepting;');
    out.push('  }');
  }
  out.push('}');
  out.push('');

  const api = transducer ? 'transduce' : 'accepts';
  out.push(`// Convenience wrapper, so every style exposes the same ${api}().`);
  out.push(`function ${api}(input) {`);
  out.push(`  return new Automaton().${api}(input);`);
  out.push('}');
  out.push('');
  out.push(`if (typeof module !== 'undefined') module.exports = { Automaton, ${api}, DELTA, START };`);
  return out.join('\n');
}

