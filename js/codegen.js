// Java's tokenizer body, indented for a class member.
function codegenJavaTokenize(ir) {
  const out = ['    private static List<String> tokenize(String input) {'];
  if (ir.isSymbolic) {
    out.push('        List<String> out = new ArrayList<>();');
    out.push('        for (int i = 0; i < input.length(); ) {');
    out.push('            int cp = input.codePointAt(i);');
    out.push('            out.add(new String(Character.toChars(cp)));');
    out.push('            i += Character.charCount(cp);');
    out.push('        }');
    out.push('        return out;');
  } else {
    out.push('        List<String> out = new ArrayList<>();');
    out.push('        for (String part : input.trim().split("\\\\s+")) {');
    out.push('            if (!part.isEmpty()) out.add(part);');
    out.push('        }');
    out.push('        return out;');
  }
  out.push('    }');
  return out;
}

function codegenJavaTable(ir, opts = {}) {
  const cls = exportIdent(opts.className || 'Automaton', 'Automaton');
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const nd = codegenIsNondeterministic(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'table' }));
  out.push('');
  out.push('import java.util.*;');
  out.push('');
  out.push(`public final class ${cls} {`);
  out.push(`    private static final String START = ${javaStr(names.get(ir.startId))};`);

  if (!codegenIsTransducer(ir)) {
    const acc = ir.states.filter(s => s.isAccept).map(s => javaStr(names.get(s.id)));
    out.push(`    private static final Set<String> ACCEPTING = new HashSet<>(Arrays.asList(${acc.join(', ')}));`);
  }

  // Java has no map literal; the table is filled in a static block.
  const valueType = nd ? 'List<String>' : (ir.machine === 'Mealy' ? 'String[]' : 'String');
  out.push(`    private static final Map<String, Map<String, ${valueType}>> DELTA = new HashMap<>();`);
  if (ir.machine === 'Moore') {
    out.push('    private static final Map<String, String> OUTPUT = new HashMap<>();');
  }
  out.push('');
  out.push('    static {');
  out.push(`        Map<String, ${valueType}> row;`);
  [...delta.entries()].forEach(([from, row]) => {
    out.push('        row = new HashMap<>();');
    [...row.entries()].forEach(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        out.push(`        row.put(${javaStr(sym)}, new String[]{${javaStr(d.to)}, ${javaStr(d.out)}});`);
      } else if (nd) {
        out.push(`        row.put(${javaStr(sym)}, Arrays.asList(${dests.map(javaStr).join(', ')}));`);
      } else {
        out.push(`        row.put(${javaStr(sym)}, ${javaStr(dests[0])});`);
      }
    });
    out.push(`        DELTA.put(${javaStr(from)}, row);`);
  });
  if (ir.machine === 'Moore') {
    ir.states.forEach(s => {
      out.push(`        OUTPUT.put(${javaStr(names.get(s.id))}, ${javaStr(s.output == null ? '' : s.output)});`);
    });
  }
  out.push('    }');
  out.push('');
  codegenJavaTokenize(ir).forEach(l => out.push(l));
  out.push('');

  if (nd) {
    out.push(`    private static final String EPSILON = ${javaStr(ir.sym.eps)};`);
    out.push('');
    out.push('    private static Set<String> epsilonClosure(Collection<String> states) {');
    out.push('        Set<String> seen = new HashSet<>(states);');
    out.push('        Deque<String> stack = new ArrayDeque<>(states);');
    out.push('        while (!stack.isEmpty()) {');
    out.push('            Map<String, List<String>> row = DELTA.get(stack.pop());');
    out.push('            if (row == null) continue;');
    out.push('            for (String target : row.getOrDefault(EPSILON, Collections.emptyList())) {');
    out.push('                if (seen.add(target)) stack.push(target);');
    out.push('            }');
    out.push('        }');
    out.push('        return seen;');
    out.push('    }');
    out.push('');
    out.push('    public static boolean accepts(String input) {');
    out.push('        Set<String> current = epsilonClosure(Collections.singletonList(START));');
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            Set<String> next = new HashSet<>();');
    out.push('            for (String state : current) {');
    out.push('                Map<String, List<String>> row = DELTA.get(state);');
    out.push('                if (row != null) next.addAll(row.getOrDefault(symbol, Collections.emptyList()));');
    out.push('            }');
    out.push('            current = epsilonClosure(next);');
    out.push('            if (current.isEmpty()) return false;');
    out.push('        }');
    out.push('        for (String state : current) if (ACCEPTING.contains(state)) return true;');
    out.push('        return false;');
    out.push('    }');
  } else if (codegenIsTransducer(ir)) {
    const sep = ir.isSymbolic ? '""' : '" "';
    out.push(`    private static final String SEP = ${sep};`);
    out.push('');
    out.push('    public static String transduce(String input) {');
    out.push('        String state = START;');
    out.push('        StringBuilder out = new StringBuilder();');
    if (ir.machine === 'Mealy') {
      // A `first` flag rather than a length check: an empty emitted symbol
      // would otherwise swallow the separator before the one after it.
      out.push('        boolean first = true;');
      out.push('        for (String symbol : tokenize(input)) {');
      out.push('            Map<String, String[]> row = DELTA.get(state);');
      out.push('            String[] edge = row == null ? null : row.get(symbol);');
      out.push('            if (edge == null) return null; // undefined transition');
      out.push('            if (!first) out.append(SEP);');
      out.push('            out.append(edge[1]);');
      out.push('            state = edge[0];');
      out.push('            first = false;');
      out.push('        }');
    } else {
      out.push('        out.append(OUTPUT.get(state));');
      out.push('        for (String symbol : tokenize(input)) {');
      out.push('            Map<String, String> row = DELTA.get(state);');
      out.push('            String next = row == null ? null : row.get(symbol);');
      out.push('            if (next == null) return null; // undefined transition');
      out.push('            state = next;');
      out.push('            out.append(SEP).append(OUTPUT.get(state));');
      out.push('        }');
    }
    out.push('        return out.toString();');
    out.push('    }');
  } else {
    out.push('    public static boolean accepts(String input) {');
    out.push('        String state = START;');
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            Map<String, String> row = DELTA.get(state);');
    out.push('            String next = row == null ? null : row.get(symbol);');
    out.push('            if (next == null) return false; // dead: no such transition');
    out.push('            state = next;');
    out.push('        }');
    out.push('        return ACCEPTING.contains(state);');
    out.push('    }');
  }

  out.push('}');
  return out.join('\n');
}

// ── Java: switch ──────────────────────────────────────────────────
// Switching on String has been legal since Java 7, so the state stays a
// readable name rather than becoming an int the reader has to decode
// against a table of constants — which would defeat the point of
// choosing this style.
function codegenJavaSwitch(ir, opts = {}) {
  const cls = exportIdent(opts.className || 'Automaton', 'Automaton');
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const transducer = codegenIsTransducer(ir);
  const order = ir.states.map(s => names.get(s.id));

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'switch' }));
  out.push('');
  out.push('import java.util.*;');
  out.push('');
  out.push(`public final class ${cls} {`);
  out.push(`    private static final String START = ${javaStr(names.get(ir.startId))};`);
  if (transducer) out.push(`    private static final String SEP = ${ir.isSymbolic ? '""' : '" "'};`);
  out.push('');
  codegenJavaTokenize(ir).forEach(l => out.push(l));
  out.push('');

  if (!transducer) {
    out.push('    private static boolean isAccepting(String state) {');
    out.push('        switch (state) {');
    ir.states.filter(s => s.isAccept).forEach(s => out.push(`            case ${javaStr(names.get(s.id))}:`));
    if (ir.states.some(s => s.isAccept)) out.push('                return true;');
    out.push('            default:');
    out.push('                return false;');
    out.push('        }');
    out.push('    }');
    out.push('');
  }

  if (ir.machine === 'Moore') {
    out.push('    private static String outputOf(String state) {');
    out.push('        switch (state) {');
    ir.states.forEach(s => {
      out.push(`            case ${javaStr(names.get(s.id))}: return ${javaStr(s.output == null ? '' : s.output)};`);
    });
    out.push('            default: return null;');
    out.push('        }');
    out.push('    }');
    out.push('');
  }

  if (nd) {
    out.push('    private static List<String> epsilonTargets(String state) {');
    out.push('        switch (state) {');
    order.forEach(name => {
      const targets = codegenEpsTargets(delta, name, eps);
      if (targets.length) {
        out.push(`            case ${javaStr(name)}: return Arrays.asList(${targets.map(javaStr).join(', ')});`);
      }
    });
    out.push('            default: return Collections.emptyList();');
    out.push('        }');
    out.push('    }');
    out.push('');
    out.push('    private static Set<String> epsilonClosure(Collection<String> states) {');
    out.push('        Set<String> seen = new HashSet<>(states);');
    out.push('        Deque<String> stack = new ArrayDeque<>(states);');
    out.push('        while (!stack.isEmpty()) {');
    out.push('            for (String target : epsilonTargets(stack.pop())) {');
    out.push('                if (seen.add(target)) stack.push(target);');
    out.push('            }');
    out.push('        }');
    out.push('        return seen;');
    out.push('    }');
    out.push('');
    out.push('    /** Adds every target of {@code state} on {@code symbol} to {@code next}. */');
    out.push('    private static void stepInto(String state, String symbol, Set<String> next) {');
    out.push('        switch (state) {');
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name).filter(([sym]) => sym !== eps);
      if (!rows.length) return;
      out.push(`            case ${javaStr(name)}:`);
      out.push('                switch (symbol) {');
      rows.forEach(([sym, dests]) => {
        out.push(`                    case ${javaStr(sym)}:`);
        dests.forEach(d => out.push(`                        next.add(${javaStr(d)});`));
        out.push('                        break;');
      });
      out.push('                }');
      out.push('                break;');
    });
    out.push('        }');
    out.push('    }');
    out.push('');
    out.push('    public static boolean accepts(String input) {');
    out.push('        Set<String> current = epsilonClosure(Collections.singletonList(START));');
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            Set<String> next = new HashSet<>();');
    out.push('            for (String state : current) stepInto(state, symbol, next);');
    out.push('            current = epsilonClosure(next);');
    out.push('            if (current.isEmpty()) return false;');
    out.push('        }');
    out.push('        for (String state : current) if (isAccepting(state)) return true;');
    out.push('        return false;');
    out.push('    }');
  } else {
    const fail = transducer ? 'null' : 'false';
    out.push(transducer
      ? '    public static String transduce(String input) {'
      : '    public static boolean accepts(String input) {');
    out.push('        String state = START;');
    if (transducer) {
      out.push('        StringBuilder out = new StringBuilder();');
      out.push('        boolean first = true;');
      if (ir.machine === 'Moore') {
        out.push('        out.append(outputOf(state));');
        out.push('        first = false;');
      }
    }
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            switch (state) {');
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name);
      out.push(`                case ${javaStr(name)}:`);
      if (!rows.length) {
        out.push(`                    return ${fail}; // no outgoing transitions`);
        return;
      }
      out.push('                    switch (symbol) {');
      rows.forEach(([sym, dests]) => {
        const d = dests[0];
        out.push(`                        case ${javaStr(sym)}:`);
        if (ir.machine === 'Mealy') {
          out.push('                            if (!first) out.append(SEP);');
          out.push(`                            out.append(${javaStr(d.out)});`);
          out.push('                            first = false;');
          out.push(`                            state = ${javaStr(d.to)};`);
        } else {
          out.push(`                            state = ${javaStr(d)};`);
        }
        out.push('                            break;');
      });
      out.push(`                        default: return ${fail};`);
      out.push('                    }');
      if (ir.machine === 'Moore') {
        out.push('                    if (!first) out.append(SEP);');
        out.push('                    out.append(outputOf(state));');
        out.push('                    first = false;');
      }
      out.push('                    break;');
    });
    out.push(`                default: return ${fail};`);
    out.push('            }');
    out.push('        }');
    out.push(transducer ? '        return out.toString();' : '        return isAccepting(state);');
    out.push('    }');
  }

  out.push('}');
  return out.join('\n');
}

// ── Java: class ───────────────────────────────────────────────────
// Instance state plus reset/step/isAccepting, with the static accepts()
// kept so the same call site works whichever style was generated.
function codegenJavaClass(ir, opts = {}) {
  const cls = exportIdent(opts.className || 'Automaton', 'Automaton');
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const transducer = codegenIsTransducer(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'class' }));
  out.push('');
  out.push('import java.util.*;');
  out.push('');
  out.push(`public final class ${cls} {`);
  out.push(`    private static final String START = ${javaStr(names.get(ir.startId))};`);
  if (!transducer) {
    const acc = ir.states.filter(s => s.isAccept).map(s => javaStr(names.get(s.id)));
    out.push(`    private static final Set<String> ACCEPTING = new HashSet<>(Arrays.asList(${acc.join(', ')}));`);
  }
  if (nd) out.push(`    private static final String EPSILON = ${javaStr(eps)};`);
  if (transducer) out.push(`    private static final String SEP = ${ir.isSymbolic ? '""' : '" "'};`);

  const valueType = nd ? 'List<String>' : (ir.machine === 'Mealy' ? 'String[]' : 'String');
  out.push(`    private static final Map<String, Map<String, ${valueType}>> DELTA = new HashMap<>();`);
  if (ir.machine === 'Moore') out.push('    private static final Map<String, String> OUTPUT = new HashMap<>();');
  out.push('');
  out.push('    static {');
  out.push(`        Map<String, ${valueType}> row;`);
  [...delta.entries()].forEach(([from, row]) => {
    out.push('        row = new HashMap<>();');
    [...row.entries()].forEach(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        out.push(`        row.put(${javaStr(sym)}, new String[]{${javaStr(d.to)}, ${javaStr(d.out)}});`);
      } else if (nd) {
        out.push(`        row.put(${javaStr(sym)}, Arrays.asList(${dests.map(javaStr).join(', ')}));`);
      } else {
        out.push(`        row.put(${javaStr(sym)}, ${javaStr(dests[0])});`);
      }
    });
    out.push(`        DELTA.put(${javaStr(from)}, row);`);
  });
  if (ir.machine === 'Moore') {
    ir.states.forEach(s => out.push(`        OUTPUT.put(${javaStr(names.get(s.id))}, ${javaStr(s.output == null ? '' : s.output)});`));
  }
  out.push('    }');
  out.push('');

  // Instance fields
  if (nd) out.push('    private Set<String> current;');
  else {
    out.push('    private String state;');
    out.push('    private boolean dead;');
  }
  if (transducer) out.push('    private final List<String> output = new ArrayList<>();');
  out.push('');
  out.push(`    public ${cls}() {`);
  out.push('        reset();');
  out.push('    }');
  out.push('');
  codegenJavaTokenize(ir).forEach(l => out.push(l));
  out.push('');

  if (nd) {
    out.push('    private static Set<String> epsilonClosure(Collection<String> states) {');
    out.push('        Set<String> seen = new HashSet<>(states);');
    out.push('        Deque<String> stack = new ArrayDeque<>(states);');
    out.push('        while (!stack.isEmpty()) {');
    out.push('            Map<String, List<String>> row = DELTA.get(stack.pop());');
    out.push('            if (row == null) continue;');
    out.push('            for (String target : row.getOrDefault(EPSILON, Collections.emptyList())) {');
    out.push('                if (seen.add(target)) stack.push(target);');
    out.push('            }');
    out.push('        }');
    out.push('        return seen;');
    out.push('    }');
    out.push('');
  }

  out.push('    /** Returns the machine to its start configuration. */');
  out.push(`    public ${cls} reset() {`);
  if (nd) out.push('        current = epsilonClosure(Collections.singletonList(START));');
  else {
    out.push('        state = START;');
    out.push('        dead = false;');
  }
  if (transducer) {
    out.push('        output.clear();');
    if (ir.machine === 'Moore') out.push('        output.add(OUTPUT.get(START));');
  }
  out.push('        return this;');
  out.push('    }');
  out.push('');

  if (nd) {
    out.push('    /** Consumes one symbol. False once no state survives. */');
    out.push('    public boolean step(String symbol) {');
    out.push('        Set<String> next = new HashSet<>();');
    out.push('        for (String s : current) {');
    out.push('            Map<String, List<String>> row = DELTA.get(s);');
    out.push('            if (row != null) next.addAll(row.getOrDefault(symbol, Collections.emptyList()));');
    out.push('        }');
    out.push('        current = epsilonClosure(next);');
    out.push('        return !current.isEmpty();');
    out.push('    }');
    out.push('');
    out.push('    public boolean isAccepting() {');
    out.push('        for (String s : current) if (ACCEPTING.contains(s)) return true;');
    out.push('        return false;');
    out.push('    }');
    out.push('');
    out.push('    /** Every state the machine could currently be in. */');
    out.push('    public Set<String> states() {');
    out.push('        return Collections.unmodifiableSet(current);');
    out.push('    }');
  } else if (ir.machine === 'Mealy') {
    out.push('    /** Consumes one symbol, returning what it emits or null. */');
    out.push('    public String step(String symbol) {');
    out.push('        Map<String, String[]> row = DELTA.get(state);');
    out.push('        String[] edge = row == null ? null : row.get(symbol);');
    out.push('        if (edge == null) { dead = true; return null; }');
    out.push('        state = edge[0];');
    out.push('        output.add(edge[1]);');
    out.push('        return edge[1];');
    out.push('    }');
  } else if (ir.machine === 'Moore') {
    out.push('    /** Consumes one symbol, returning the new state\'s output. */');
    out.push('    public String step(String symbol) {');
    out.push('        Map<String, String> row = DELTA.get(state);');
    out.push('        String next = row == null ? null : row.get(symbol);');
    out.push('        if (next == null) { dead = true; return null; }');
    out.push('        state = next;');
    out.push('        String emitted = OUTPUT.get(state);');
    out.push('        output.add(emitted);');
    out.push('        return emitted;');
    out.push('    }');
  } else {
    out.push('    /** Consumes one symbol. False if it kills the run. */');
    out.push('    public boolean step(String symbol) {');
    out.push('        Map<String, String> row = DELTA.get(state);');
    out.push('        String next = row == null ? null : row.get(symbol);');
    out.push('        if (next == null) { dead = true; return false; }');
    out.push('        state = next;');
    out.push('        return true;');
    out.push('    }');
    out.push('');
    out.push('    public boolean isAccepting() {');
    out.push('        return !dead && ACCEPTING.contains(state);');
    out.push('    }');
  }

  out.push('');
  if (transducer) {
    out.push('    public String run(String input) {');
    out.push('        reset();');
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            if (step(symbol) == null) return null;');
    out.push('        }');
    out.push('        StringBuilder sb = new StringBuilder();');
    out.push('        for (int i = 0; i < output.size(); i++) {');
    out.push('            if (i > 0) sb.append(SEP);');
    out.push('            sb.append(output.get(i));');
    out.push('        }');
    out.push('        return sb.toString();');
    out.push('    }');
    out.push('');
    out.push('    public static String transduce(String input) {');
    out.push(`        return new ${cls}().run(input);`);
    out.push('    }');
  } else {
    out.push('    public boolean run(String input) {');
    out.push('        reset();');
    out.push('        for (String symbol : tokenize(input)) {');
    out.push('            if (!step(symbol)) return false;');
    out.push('        }');
    out.push('        return isAccepting();');
    out.push('    }');
    out.push('');
    out.push('    /** Kept static so the call site matches the other styles. */');
    out.push('    public static boolean accepts(String input) {');
    out.push(`        return new ${cls}().run(input);`);
    out.push('    }');
  }

  out.push('}');
  return out.join('\n');
}

// ══════════════════════════════════════════════════════════════════
//  C
// ══════════════════════════════════════════════════════════════════
//  Narrower than the others on purpose. C has no string map, so the
//  clean, genuinely idiomatic output is a dense table indexed by state
//  and symbol — which needs every symbol to be one byte. Word-length
//  alphabets and nondeterminism both push this into building a hash
//  map and a subset simulator in C, and the result would be neither
//  readable nor obviously correct.
function codegenC(ir, opts = {}) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '/*');

  if (ir.machine !== 'DFA') {
    return codegenUnsupported(
      `C generation covers deterministic finite automata only. ${ir.machineLabel} needs either a `
      + `subset simulation or an output function, which in C means hand-rolling a string map — `
      + `use the JavaScript, Python or Java target instead.`, '//');
  }
  const oneByte = ir.sigma.every(s => [...s].length === 1 && s.charCodeAt(0) < 128);
  if (!oneByte) {
    return codegenUnsupported(
      'C generation needs every input symbol to be a single ASCII character, because the '
      + 'transition table is indexed directly by symbol. This alphabet has multi-character or '
      + 'non-ASCII symbols — use the JavaScript, Python or Java target instead.', '//');
  }

  const style = codegenStyle(opts);
  if (style === 'switch') return codegenCSwitch(ir, opts);
  if (style === 'class') return codegenCStruct(ir, opts);
  return codegenCTable(ir, opts);
}

// State ids, index map, sorted Σ, and the dense δ table — everything the
// three C emitters agree on. -1 is the dead state.
function codegenCShape(ir) {
  const names = exportUniqueIdents(ir.states, s => s.toUpperCase());
  const order = ir.states.map(s => s.id);
  const idx = new Map(order.map((id, i) => [id, i]));
  const sigma = [...ir.sigma].sort();
  const table = order.map(id => sigma.map(sym => {
    const t = ir.transitions.find(x => x.from === id && x.symbol === sym);
    return t ? idx.get(t.to) : -1;
  }));
  const accIdx = ir.states.filter(s => s.isAccept).map(s => idx.get(s.id));
  return { names, order, idx, sigma, table, accIdx };
}

// A C character literal for a Σ symbol, with the two that need escaping.
function codegenCChar(s) {
  return `'${s === "'" ? "\\'" : s === '\\' ? '\\\\' : s}'`;
}

function codegenCTable(ir, opts = {}) {
  const { names, order, idx, sigma, table, accIdx } = codegenCShape(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'table' }));
  out.push('');
  out.push('#include <stdbool.h>');
  out.push('#include <stddef.h>');
  out.push('');
  out.push(`#define STATE_COUNT ${order.length}`);
  out.push(`#define SYMBOL_COUNT ${sigma.length}`);
  out.push('');
  out.push('// State indices, in canvas order.');
  order.forEach((id, i) => out.push(`#define ${names.get(id)} ${i}`));
  out.push('');
  out.push(`static const char SYMBOLS[SYMBOL_COUNT] = {${sigma.map(codegenCChar).join(', ')}};`);
  out.push('');
  out.push('// DELTA[state][symbol index]; -1 means no transition (reject).');
  out.push('static const int DELTA[STATE_COUNT][SYMBOL_COUNT] = {');
  table.forEach((row, i) => {
    out.push(`    {${row.map(v => String(v).padStart(2)).join(', ')}},  // ${ir.states[i].name}`);
  });
  out.push('};');
  out.push('');
  out.push(`static const int ACCEPTING[] = {${accIdx.length ? accIdx.join(', ') : '-1'}};`);
  out.push(`static const size_t ACCEPTING_COUNT = ${accIdx.length};`);
  out.push('');
  out.push('static int symbol_index(char c) {');
  out.push('    for (int i = 0; i < SYMBOL_COUNT; i++) {');
  out.push('        if (SYMBOLS[i] == c) return i;');
  out.push('    }');
  out.push('    return -1;');
  out.push('}');
  out.push('');
  out.push('bool automaton_accepts(const char *input) {');
  out.push(`    int state = ${names.get(ir.startId)};`);
  out.push('    for (const char *p = input; *p; p++) {');
  out.push('        int s = symbol_index(*p);');
  out.push('        if (s < 0) return false;  // symbol not in the alphabet');
  out.push('        state = DELTA[state][s];');
  out.push('        if (state < 0) return false;  // dead: no such transition');
  out.push('    }');
  out.push('    for (size_t i = 0; i < ACCEPTING_COUNT; i++) {');
  out.push('        if (ACCEPTING[i] == state) return true;');
  out.push('    }');
  out.push('    return false;');
  out.push('}');
  return out.join('\n');
}

// ── C: switch ─────────────────────────────────────────────────────
// No tables at all — δ is nested switches on the state and the byte.
// This is the shape you write by hand for a protocol or lexer inner
// loop: the compiler turns it into a jump table, and nothing is
// dereferenced per symbol.
function codegenCSwitch(ir, opts = {}) {
  const { names, order, sigma, table, accIdx } = codegenCShape(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', { ...opts, style: 'switch' }));
  out.push('');
  out.push('#include <stdbool.h>');
  out.push('');
  out.push('// State indices, in canvas order.');
  out.push('enum {');
  order.forEach((id, i) => out.push(`    ${names.get(id)} = ${i},`));
  out.push('};');
  out.push('');
  out.push('bool automaton_accepts(const char *input) {');
  out.push(`    int state = ${names.get(ir.startId)};`);
  out.push('    for (const char *p = input; *p; p++) {');
  out.push('        switch (state) {');
  order.forEach((id, i) => {
    out.push(`        case ${names.get(id)}:`);
    const live = table[i].map((dest, k) => [sigma[k], dest]).filter(([, dest]) => dest >= 0);
    if (!live.length) {
      out.push('            return false;  // no outgoing transitions');
      return;
    }
    out.push('            switch (*p) {');
    live.forEach(([sym, dest]) => {
      out.push(`            case ${codegenCChar(sym)}: state = ${names.get(order[dest])}; break;`);
    });
    out.push('            default: return false;  // dead: no such transition');
    out.push('            }');
    out.push('            break;');
  });
  out.push('        default: return false;');
  out.push('        }');
  out.push('    }');
  out.push('    switch (state) {');
  if (accIdx.length) {
    accIdx.forEach(i => out.push(`    case ${names.get(order[i])}:`));
    out.push('        return true;');
  }
  out.push('    default:');
  out.push('        return false;');
  out.push('    }');
  out.push('}');
  return out.join('\n');
}

// ── C: struct handle ──────────────────────────────────────────────
// C has no classes, so the class style becomes the pattern C actually
// uses for the same job: a small struct the caller owns, plus functions
// taking a pointer to it. That is what lets input arrive incrementally
// — one byte per interrupt, per read(), per event — rather than as one
// whole string.
function codegenCStruct(ir, opts = {}) {
  const { names, order, sigma, table, accIdx } = codegenCShape(ir);

  const out = [];
  out.push(codegenBanner(ir, '//', {
    ...opts, style: 'class',
    extraNote: 'C has no classes; this is the equivalent struct-and-functions handle.'
  }));
  out.push('');
  out.push('#include <stdbool.h>');
  out.push('#include <stddef.h>');
  out.push('');
  out.push(`#define STATE_COUNT ${order.length}`);
  out.push(`#define SYMBOL_COUNT ${sigma.length}`);
  out.push('');
  out.push('// State indices, in canvas order.');
  out.push('enum {');
  order.forEach((id, i) => out.push(`    ${names.get(id)} = ${i},`));
  out.push('};');
  out.push('');
  out.push(`static const char SYMBOLS[SYMBOL_COUNT] = {${sigma.map(codegenCChar).join(', ')}};`);
  out.push('');
  out.push('// DELTA[state][symbol index]; -1 means no transition (reject).');
  out.push('static const int DELTA[STATE_COUNT][SYMBOL_COUNT] = {');
  table.forEach((row, i) => {
    out.push(`    {${row.map(v => String(v).padStart(2)).join(', ')}},  // ${ir.states[i].name}`);
  });
  out.push('};');
  out.push('');
  out.push(`static const int ACCEPTING[] = {${accIdx.length ? accIdx.join(', ') : '-1'}};`);
  out.push(`static const size_t ACCEPTING_COUNT = ${accIdx.length};`);
  out.push('');
  out.push('typedef struct {');
  out.push('    int state;  // current state, or -1 once the run is dead');
  out.push('} automaton_t;');
  out.push('');
  out.push('static int symbol_index(char c) {');
  out.push('    for (int i = 0; i < SYMBOL_COUNT; i++) {');
  out.push('        if (SYMBOLS[i] == c) return i;');
  out.push('    }');
  out.push('    return -1;');
  out.push('}');
  out.push('');
  out.push('/** Returns the machine to its start configuration. */');
  out.push('void automaton_reset(automaton_t *m) {');
  out.push(`    m->state = ${names.get(ir.startId)};`);
  out.push('}');
  out.push('');
  out.push('/** Consumes one byte. Returns false once the run is dead. */');
  out.push('bool automaton_step(automaton_t *m, char c) {');
  out.push('    if (m->state < 0) return false;');
  out.push('    int s = symbol_index(c);');
  out.push('    if (s < 0) { m->state = -1; return false; }  // not in the alphabet');
  out.push('    m->state = DELTA[m->state][s];');
  out.push('    return m->state >= 0;');
  out.push('}');
  out.push('');
  out.push('bool automaton_is_accepting(const automaton_t *m) {');
  out.push('    if (m->state < 0) return false;');
  out.push('    for (size_t i = 0; i < ACCEPTING_COUNT; i++) {');
  out.push('        if (ACCEPTING[i] == m->state) return true;');
  out.push('    }');
  out.push('    return false;');
  out.push('}');
  out.push('');
  out.push('/** Convenience: run a whole NUL-terminated string. */');
  out.push('bool automaton_accepts(const char *input) {');
  out.push('    automaton_t m;');
  out.push('    automaton_reset(&m);');
  out.push('    for (const char *p = input; *p; p++) {');
  out.push('        if (!automaton_step(&m, *p)) return false;');
  out.push('    }');
  out.push('    return automaton_is_accepting(&m);');
  out.push('}');
  return out.join('\n');
}

// ══════════════════════════════════════════════════════════════════
//  XSTATE
// ══════════════════════════════════════════════════════════════════
//  XState dispatches one event to one target, so a nondeterministic
//  machine has no faithful config — determinise it first.
function codegenXState(ir) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '//');
  if (codegenIsNondeterministic(ir)) {
    return codegenUnsupported(
      'XState resolves one event to one target, so a nondeterministic machine cannot be expressed '
      + 'directly. Run Algorithms › NFA → DFA (subset construction) first, then export the result.', '//');
  }

  const names = codegenNames(ir);
  const states = {};
  ir.states.forEach(s => {
    const name = names.get(s.id);
    const on = {};
    ir.transitions.filter(t => t.from === s.id).forEach(t => {
      // Event names are the input symbols; XState treats them as opaque strings.
      if (ir.machine === 'Mealy') {
        on[t.symbol] = { target: names.get(t.to), actions: [{ type: 'emit', params: { output: t.output == null ? '' : t.output } }] };
      } else {
        on[t.symbol] = names.get(t.to);
      }
    });
    const node = {};
    if (Object.keys(on).length) node.on = on;
    // Accepting is not an XState concept; carry it as metadata rather than
    // pretending it is a final state, which would halt the machine.
    const meta = {};
    if (s.isAccept) meta.accepting = true;
    if (ir.machine === 'Moore' && s.output != null && s.output !== '') meta.output = s.output;
    if (Object.keys(meta).length) node.meta = meta;
    states[name] = node;
  });

  const config = {
    id: exportIdent(ir.machine, 'automaton').toLowerCase(),
    initial: names.get(ir.startId),
    states
  };

  return [
    codegenBanner(ir, '//'),
    '// Accepting states are marked in `meta.accepting` — XState has no',
    '// accept notion, and a `final` state would stop the machine instead.',
    '',
    `export const machine = ${JSON.stringify(config, null, 2)};`,
    ''
  ].join('\n');
}

// ══════════════════════════════════════════════════════════════════
//  SCXML  (W3C State Chart XML)
// ══════════════════════════════════════════════════════════════════
function codegenSCXML(ir) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '<!--');

  const names = codegenNames(ir);
  const out = [];
  out.push('<?xml version="1.0" encoding="UTF-8"?>');
  out.push(`<!-- ${codegenBanner(ir, '').trim().split('\n').join(' | ').trim()} -->`);
  out.push('<scxml xmlns="http://www.w3.org/2005/07/scxml" version="1.0"'
    + ` initial="${xmlAttr(names.get(ir.startId))}" datamodel="ecmascript">`);

  ir.states.forEach(s => {
    const name = names.get(s.id);
    const edges = ir.transitions.filter(t => t.from === s.id);
    // Accepting states stay <state>, not <final>: entering a <final> ends
    // the machine, but an accepting state here can still be left.
    const attrs = `id="${xmlAttr(name)}"`;
    if (!edges.length && !s.isAccept && ir.machine !== 'Moore') {
      out.push(`  <state ${attrs}/>`);
      return;
    }
    out.push(`  <state ${attrs}>`);
    if (s.isAccept) out.push('    <datamodel><data id="accepting" expr="true"/></datamodel>');
    if (ir.machine === 'Moore' && s.output != null && s.output !== '') {
      out.push(`    <onentry><log label="output" expr="${xmlAttr(JSON.stringify(s.output))}"/></onentry>`);
    }
    edges.forEach(t => {
      const ev = xmlAttr(t.symbol);
      const target = xmlAttr(names.get(t.to));
      if (ir.machine === 'Mealy') {
        out.push(`    <transition event="${ev}" target="${target}">`);
        out.push(`      <log label="output" expr="${xmlAttr(JSON.stringify(t.output == null ? '' : t.output))}"/>`);
        out.push('    </transition>');
      } else {
        out.push(`    <transition event="${ev}" target="${target}"/>`);
      }
    });
    out.push('  </state>');
  });

  out.push('</scxml>');
  return out.join('\n');
}

// ══════════════════════════════════════════════════════════════════
//  TEST SUITES
// ══════════════════════════════════════════════════════════════════
//  The generated cases come from exportSampleWords, so they are derived
//  from the machine rather than written by hand — the same idea as
//  model-based test generation. Pair with the JavaScript/Python target
//  and the suite runs against generated source.
function codegenJest(ir, opts = {}) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '//');
  if (codegenIsTransducer(ir)) {
    return codegenUnsupported(
      'Test generation asserts membership in L(M). A transducer has no accept/reject notion '
      + 'unless "transducers accept" is enabled in Settings.', '//');
  }

  const samples = exportSampleWords(opts);
  const acc = samples.accepted.map(w => exportWordText(w, ir));
  const rej = samples.rejected.map(w => exportWordText(w, ir));
  const mod = opts.module || './automaton';

  return [
    codegenBanner(ir, '//'),
    '// Cases are derived from the machine itself, in shortlex order.',
    '',
    `const { accepts } = require(${jsStr(mod)});`,
    '',
    `describe(${jsStr(`L(M) — ${ir.machineLabel}`)}, () => {`,
    acc.length ? `  test.each([\n${acc.map(w => `    ${jsStr(w)},`).join('\n')}\n  ])('accepts %j', (word) => {\n    expect(accepts(word)).toBe(true);\n  });` : '  // no accepted words found within the search budget',
    '',
    rej.length ? `  test.each([\n${rej.map(w => `    ${jsStr(w)},`).join('\n')}\n  ])('rejects %j', (word) => {\n    expect(accepts(word)).toBe(false);\n  });` : '  // no rejected words found within the search budget',
    '});',
    ''
  ].join('\n');
}

function codegenPytest(ir, opts = {}) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '#');
  if (codegenIsTransducer(ir)) {
    return codegenUnsupported(
      'Test generation asserts membership in L(M). A transducer has no accept/reject notion '
      + 'unless "transducers accept" is enabled in Settings.', '#');
  }

  const samples = exportSampleWords(opts);
  const acc = samples.accepted.map(w => exportWordText(w, ir));
  const rej = samples.rejected.map(w => exportWordText(w, ir));
  const mod = (opts.module || 'automaton').replace(/^\.\//, '').replace(/\.py$/, '');

  const out = [];
  out.push(codegenBanner(ir, '#'));
  out.push('# Cases are derived from the machine itself, in shortlex order.');
  out.push('');
  out.push('import pytest');
  out.push('');
  out.push(`from ${mod} import accepts`);
  out.push('');
  out.push('');
  if (acc.length) {
    out.push(`@pytest.mark.parametrize('word', [\n${acc.map(w => `    ${pyStr(w)},`).join('\n')}\n])`);
    out.push('def test_accepts(word):');
    out.push('    assert accepts(word) is True');
    out.push('');
    out.push('');
  }
  if (rej.length) {
    out.push(`@pytest.mark.parametrize('word', [\n${rej.map(w => `    ${pyStr(w)},`).join('\n')}\n])`);
    out.push('def test_rejects(word):');
    out.push('    assert accepts(word) is False');
    out.push('');
  }
  return out.join('\n');
}

