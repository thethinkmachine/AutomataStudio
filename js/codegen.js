function codegenPython(ir, opts = {}) {
  const support = codegenSupport(ir);
  if (!support.ok) return codegenUnsupported(support.reason, '#');
  const style = codegenStyle(opts);
  if (style === 'switch') return codegenPySwitch(ir, opts);
  if (style === 'class') return codegenPyClass(ir, opts);
  return codegenPyTable(ir, opts);
}

function codegenPyTokenize(ir) {
  return [
    'def tokenize(text):',
    ir.isSymbolic ? '    return list(text)' : '    return text.split()'
  ];
}

function codegenPyTable(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const accepting = ir.states.filter(s => s.isAccept).map(s => names.get(s.id));
  const nd = codegenIsNondeterministic(ir);

  const out = [];
  out.push(codegenBanner(ir, '#', { ...opts, style: 'table' }));
  out.push('');
  out.push('DELTA = {');
  [...delta.entries()].forEach(([from, row]) => {
    if (!row.size) { out.push(`    ${pyStr(from)}: {},`); return; }
    const cells = [...row.entries()].map(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        return `${pyStr(sym)}: (${pyStr(d.to)}, ${pyStr(d.out)})`;
      }
      return `${pyStr(sym)}: ${nd ? `(${dests.map(pyStr).join(', ')}${dests.length === 1 ? ',' : ''})` : pyStr(dests[0])}`;
    });
    out.push(`    ${pyStr(from)}: {${cells.join(', ')}},`);
  });
  out.push('}');
  out.push('');
  out.push(`START = ${pyStr(start)}`);
  if (!codegenIsTransducer(ir)) {
    out.push(`ACCEPTING = frozenset({${accepting.map(pyStr).join(', ')}})`);
  }
  if (ir.machine === 'Moore') {
    out.push('');
    out.push('# Moore output is a property of the state, not the edge.');
    out.push('OUTPUT = {');
    ir.states.forEach(s => out.push(`    ${pyStr(names.get(s.id))}: ${pyStr(s.output == null ? '' : s.output)},`));
    out.push('}');
  }
  out.push('');
  codegenPyTokenize(ir).forEach(l => out.push(l));
  out.push('');
  out.push('');

  if (nd) {
    out.push(`EPSILON = ${pyStr(ir.sym.eps)}`);
    out.push('');
    out.push('');
    out.push('def epsilon_closure(states):');
    out.push('    seen = set(states)');
    out.push('    stack = list(states)');
    out.push('    while stack:');
    out.push('        state = stack.pop()');
    out.push('        for target in DELTA.get(state, {}).get(EPSILON, ()):');
    out.push('            if target not in seen:');
    out.push('                seen.add(target)');
    out.push('                stack.append(target)');
    out.push('    return seen');
    out.push('');
    out.push('');
    out.push('def accepts(text):');
    out.push('    current = epsilon_closure({START})');
    out.push('    for symbol in tokenize(text):');
    out.push('        nxt = set()');
    out.push('        for state in current:');
    out.push('            nxt.update(DELTA.get(state, {}).get(symbol, ()))');
    out.push('        current = epsilon_closure(nxt)');
    out.push('        if not current:');
    out.push('            return False');
    out.push('    return bool(current & ACCEPTING)');
  } else if (ir.machine === 'Mealy') {
    out.push('def transduce(text):');
    out.push('    state = START');
    out.push('    output = []');
    out.push('    for symbol in tokenize(text):');
    out.push('        edge = DELTA.get(state, {}).get(symbol)');
    out.push('        if edge is None:');
    out.push('            return None  # undefined transition');
    out.push('        output.append(edge[1])');
    out.push('        state = edge[0]');
    out.push(`    return ${ir.isSymbolic ? "''" : "' '"}.join(output)`);
  } else if (ir.machine === 'Moore') {
    out.push('def transduce(text):');
    out.push('    state = START');
    out.push('    output = [OUTPUT[state]]');
    out.push('    for symbol in tokenize(text):');
    out.push('        nxt = DELTA.get(state, {}).get(symbol)');
    out.push('        if nxt is None:');
    out.push('            return None  # undefined transition');
    out.push('        state = nxt');
    out.push('        output.append(OUTPUT[state])');
    out.push(`    return ${ir.isSymbolic ? "''" : "' '"}.join(output)`);
  } else {
    out.push('def accepts(text):');
    out.push('    state = START');
    out.push('    for symbol in tokenize(text):');
    out.push('        nxt = DELTA.get(state, {}).get(symbol)');
    out.push('        if nxt is None:');
    out.push('            return False  # dead: no such transition');
    out.push('        state = nxt');
    out.push('    return state in ACCEPTING');
  }
  out.push('');
  return out.join('\n');
}

// ── Python: match/case ────────────────────────────────────────────
// `match` is Python's switch, and the direct translation of the nested
// control flow the other languages get. Note the version floor: match
// landed in 3.10, so this style says so in the banner rather than
// failing at import time on an older interpreter.
//
// Every pattern here is a string literal. A bare name in a case would
// be a capture pattern — it would match anything and bind, silently
// turning the state machine into an unconditional branch.
function codegenPySwitch(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const transducer = codegenIsTransducer(ir);
  const order = ir.states.map(s => names.get(s.id));

  const out = [];
  out.push(codegenBanner(ir, '#', { ...opts, style: 'switch', extraNote: 'Requires Python 3.10+ for the match statement.' }));
  out.push('');
  out.push(`START = ${pyStr(start)}`);
  out.push('');
  out.push('');
  codegenPyTokenize(ir).forEach(l => out.push(l));
  out.push('');
  out.push('');

  if (!transducer) {
    out.push('def is_accepting(state):');
    out.push('    match state:');
    const accs = ir.states.filter(s => s.isAccept).map(s => pyStr(names.get(s.id)));
    if (accs.length) {
      out.push(`        case ${accs.join(' | ')}:`);
      out.push('            return True');
    }
    out.push('        case _:');
    out.push('            return False');
    out.push('');
    out.push('');
  }

  if (ir.machine === 'Moore') {
    out.push('def output_of(state):');
    out.push('    match state:');
    ir.states.forEach(s => {
      out.push(`        case ${pyStr(names.get(s.id))}:`);
      out.push(`            return ${pyStr(s.output == null ? '' : s.output)}`);
    });
    out.push('        case _:');
    out.push('            return None');
    out.push('');
    out.push('');
  }

  if (nd) {
    out.push('def epsilon_targets(state):');
    out.push('    match state:');
    let anyEps = false;
    order.forEach(name => {
      const targets = codegenEpsTargets(delta, name, eps);
      if (!targets.length) return;
      anyEps = true;
      out.push(`        case ${pyStr(name)}:`);
      out.push(`            return (${targets.map(pyStr).join(', ')}${targets.length === 1 ? ',' : ''})`);
    });
    if (!anyEps) out.push('        # this machine has no ε-transitions');
    out.push('        case _:');
    out.push('            return ()');
    out.push('');
    out.push('');
    out.push('def epsilon_closure(states):');
    out.push('    seen = set(states)');
    out.push('    stack = list(states)');
    out.push('    while stack:');
    out.push('        for target in epsilon_targets(stack.pop()):');
    out.push('            if target not in seen:');
    out.push('                seen.add(target)');
    out.push('                stack.append(target)');
    out.push('    return seen');
    out.push('');
    out.push('');
    out.push('def step_into(state, symbol, nxt):');
    out.push('    """Adds every target of `state` on `symbol` to `nxt`."""');
    out.push('    match state:');
    let anyRows = false;
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name).filter(([sym]) => sym !== eps);
      if (!rows.length) return;
      anyRows = true;
      out.push(`        case ${pyStr(name)}:`);
      out.push('            match symbol:');
      rows.forEach(([sym, dests]) => {
        out.push(`                case ${pyStr(sym)}:`);
        out.push(`                    nxt.update((${dests.map(pyStr).join(', ')}${dests.length === 1 ? ',' : ''}))`);
      });
    });
    if (!anyRows) out.push('        case _:');
    if (!anyRows) out.push('            pass');
    out.push('');
    out.push('');
    out.push('def accepts(text):');
    out.push('    current = epsilon_closure({START})');
    out.push('    for symbol in tokenize(text):');
    out.push('        nxt = set()');
    out.push('        for state in current:');
    out.push('            step_into(state, symbol, nxt)');
    out.push('        current = epsilon_closure(nxt)');
    out.push('        if not current:');
    out.push('            return False');
    out.push('    return any(is_accepting(state) for state in current)');
  } else {
    const fail = transducer ? 'None' : 'False';
    out.push(transducer ? 'def transduce(text):' : 'def accepts(text):');
    out.push('    state = START');
    if (transducer) out.push(ir.machine === 'Moore' ? '    output = [output_of(state)]' : '    output = []');
    out.push('    for symbol in tokenize(text):');
    out.push('        match state:');
    order.forEach(name => {
      const rows = codegenRowsFor(delta, name);
      out.push(`            case ${pyStr(name)}:`);
      if (!rows.length) {
        out.push(`                return ${fail}  # no outgoing transitions`);
        return;
      }
      out.push('                match symbol:');
      rows.forEach(([sym, dests]) => {
        const d = dests[0];
        out.push(`                    case ${pyStr(sym)}:`);
        if (ir.machine === 'Mealy') {
          out.push(`                        output.append(${pyStr(d.out)})`);
          out.push(`                        state = ${pyStr(d.to)}`);
        } else {
          out.push(`                        state = ${pyStr(d)}`);
        }
      });
      out.push('                    case _:');
      out.push(`                        return ${fail}`);
      if (ir.machine === 'Moore') out.push('                output.append(output_of(state))');
    });
    out.push('            case _:');
    out.push(`                return ${fail}`);
    out.push(transducer
      ? `    return ${ir.isSymbolic ? "''" : "' '"}.join(output)`
      : '    return is_accepting(state)');
  }

  out.push('');
  return out.join('\n');
}

// ── Python: class ─────────────────────────────────────────────────
function codegenPyClass(ir, opts = {}) {
  const names = codegenNames(ir);
  const delta = codegenDelta(ir, names);
  const start = names.get(ir.startId);
  const accepting = ir.states.filter(s => s.isAccept).map(s => names.get(s.id));
  const eps = ir.sym.eps;
  const nd = codegenIsNondeterministic(ir);
  const transducer = codegenIsTransducer(ir);
  const join = ir.isSymbolic ? "''" : "' '";

  const out = [];
  out.push(codegenBanner(ir, '#', { ...opts, style: 'class' }));
  out.push('');
  out.push('DELTA = {');
  [...delta.entries()].forEach(([from, row]) => {
    if (!row.size) { out.push(`    ${pyStr(from)}: {},`); return; }
    const cells = [...row.entries()].map(([sym, dests]) => {
      if (ir.machine === 'Mealy') {
        const d = dests[0];
        return `${pyStr(sym)}: (${pyStr(d.to)}, ${pyStr(d.out)})`;
      }
      return `${pyStr(sym)}: ${nd ? `(${dests.map(pyStr).join(', ')}${dests.length === 1 ? ',' : ''})` : pyStr(dests[0])}`;
    });
    out.push(`    ${pyStr(from)}: {${cells.join(', ')}},`);
  });
  out.push('}');
  out.push('');
  out.push(`START = ${pyStr(start)}`);
  if (!transducer) out.push(`ACCEPTING = frozenset({${accepting.map(pyStr).join(', ')}})`);
  if (nd) out.push(`EPSILON = ${pyStr(eps)}`);
  if (ir.machine === 'Moore') {
    out.push('OUTPUT = {');
    ir.states.forEach(s => out.push(`    ${pyStr(names.get(s.id))}: ${pyStr(s.output == null ? '' : s.output)},`));
    out.push('}');
  }
  out.push('');
  out.push('');
  codegenPyTokenize(ir).forEach(l => out.push(l));
  out.push('');
  out.push('');

  if (nd) {
    out.push('def epsilon_closure(states):');
    out.push('    seen = set(states)');
    out.push('    stack = list(states)');
    out.push('    while stack:');
    out.push('        state = stack.pop()');
    out.push('        for target in DELTA.get(state, {}).get(EPSILON, ()):');
    out.push('            if target not in seen:');
    out.push('                seen.add(target)');
    out.push('                stack.append(target)');
    out.push('    return seen');
    out.push('');
    out.push('');
  }

  out.push('class Automaton:');
  out.push('    """Stateful recogniser: feed it one symbol at a time."""');
  out.push('');
  out.push('    def __init__(self):');
  out.push('        self.reset()');
  out.push('');
  out.push('    def reset(self):');
  if (nd) {
    out.push('        self.current = epsilon_closure({START})');
  } else {
    out.push('        self.state = START');
    out.push('        self.dead = False');
  }
  if (transducer) out.push(ir.machine === 'Moore' ? '        self.output = [OUTPUT[START]]' : '        self.output = []');
  out.push('        return self');
  out.push('');

  if (nd) {
    out.push('    def step(self, symbol):');
    out.push('        """Consumes one symbol. False once no state survives."""');
    out.push('        nxt = set()');
    out.push('        for state in self.current:');
    out.push('            nxt.update(DELTA.get(state, {}).get(symbol, ()))');
    out.push('        self.current = epsilon_closure(nxt)');
    out.push('        return bool(self.current)');
    out.push('');
    out.push('    @property');
    out.push('    def is_accepting(self):');
    out.push('        return bool(self.current & ACCEPTING)');
    out.push('');
    out.push('    @property');
    out.push('    def states(self):');
    out.push('        """Every state the machine could currently be in."""');
    out.push('        return frozenset(self.current)');
  } else if (ir.machine === 'Mealy') {
    out.push('    def step(self, symbol):');
    out.push('        """Consumes one symbol, returning what it emits or None."""');
    out.push('        edge = DELTA.get(self.state, {}).get(symbol)');
    out.push('        if edge is None:');
    out.push('            self.dead = True');
    out.push('            return None');
    out.push('        self.state, emitted = edge');
    out.push('        self.output.append(emitted)');
    out.push('        return emitted');
  } else if (ir.machine === 'Moore') {
    out.push('    def step(self, symbol):');
    out.push('        """Consumes one symbol, returning the new state\'s output."""');
    out.push('        nxt = DELTA.get(self.state, {}).get(symbol)');
    out.push('        if nxt is None:');
    out.push('            self.dead = True');
    out.push('            return None');
    out.push('        self.state = nxt');
    out.push('        emitted = OUTPUT[self.state]');
    out.push('        self.output.append(emitted)');
    out.push('        return emitted');
  } else {
    out.push('    def step(self, symbol):');
    out.push('        """Consumes one symbol. False if it kills the run."""');
    out.push('        nxt = DELTA.get(self.state, {}).get(symbol)');
    out.push('        if nxt is None:');
    out.push('            self.dead = True');
    out.push('            return False');
    out.push('        self.state = nxt');
    out.push('        return True');
    out.push('');
    out.push('    @property');
    out.push('    def is_accepting(self):');
    out.push('        return not self.dead and self.state in ACCEPTING');
  }

  out.push('');
  if (transducer) {
    out.push('    def transduce(self, text):');
    out.push('        self.reset()');
    out.push('        for symbol in tokenize(text):');
    out.push('            if self.step(symbol) is None:');
    out.push('                return None');
    out.push(`        return ${join}.join(self.output)`);
  } else {
    out.push('    def accepts(self, text):');
    out.push('        self.reset()');
    out.push('        for symbol in tokenize(text):');
    out.push('            if not self.step(symbol):');
    out.push('                return False');
    out.push('        return self.is_accepting');
  }

  out.push('');
  out.push('');
  const api = transducer ? 'transduce' : 'accepts';
  out.push(`# Convenience wrapper, so every style exposes the same ${api}().`);
  out.push(`def ${api}(text):`);
  out.push(`    return Automaton().${api}(text)`);
  out.push('');
  return out.join('\n');
}

